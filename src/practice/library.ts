type ItemInput = Omit<PracticeItem, 'revision' | 'kind' | 'cue' | 'source' | 'topicIds'> & {
  revision?: number;
  quote: string;
  adapted?: boolean;
  topicIds?: string[];
};

function item(
  kind: PracticeItem['kind'],
  cue: string,
  { quote, adapted = false, revision = 1, ...content }: ItemInput,
): PracticeItem {
  return {
    ...content,
    revision,
    kind,
    cue,
    topicIds: content.topicIds ?? originalTopics[content.id] ?? (content.id.startsWith('verb-opstaan-')
      ? ['past-tense', 'daily-life', 'separable-verbs']
      : content.id.startsWith('verb-gaan-') ? ['past-tense', 'travel'] : ['daily-life']),
    source: { label: sourceLabels[content.lessonId], quote, adapted },
  };
}

