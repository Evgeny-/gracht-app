type VocabularyInput = Omit<ItemInput, 'answer' | 'prompt'> & { word: string; prompt?: string };
function vocabulary({ word, prompt, ...content }: VocabularyInput): PracticeItem {
  return recall({
    ...content,
    answer: word === content.dutch ? word : `${word} · ${content.dutch}`,
    prompt: prompt ?? (word === content.dutch
      ? `How do you say “${content.title.replace(/\?$/, '')}”?`
      : `Say “${content.title.toLowerCase()}” in Dutch. Then use it in a short sentence.`),
  });
}

type SentenceInput = Omit<ItemInput, 'answer' | 'prompt'> & { prompt?: string };
function sentence({ prompt, ...content }: SentenceInput): PracticeItem {
  return build({
    ...content,
    prompt: prompt ?? content.english,
    answer: content.dutch,
    acceptedAnswers: content.acceptedAnswers ?? [content.dutch],
  });
}

function verbPair(content: {
  verb: string; person: string; lessonId: string; quote: string; topicIds: string[];
  models: [string, string, string]; translations: [string, string]; explanations: [string, string];
}): PracticeItem[] {
  const reference = content.models.map((dutch, index) => ({ label: ['Today', 'Yesterday', 'Completed'][index], dutch }));
  return (['past', 'completed'] as const).map((form, index) => item('verb', index === 0 ? 'Change the time' : 'Make it a completed action', {
    id: `verb-${content.verb}-${form}-${content.person}`,
    lessonId: content.lessonId,
    topicIds: content.topicIds,
    title: content.translations[index],
    prompt: `${index === 0 ? content.models[0] : content.models[0].replace(' vandaag', '')} ${index === 0 ? 'Say this about yesterday.' : 'Say this as a completed action.'}`,
    answer: content.models[index + 1],
    explanation: content.explanations[index],
    dutch: content.models[index + 1],
    english: content.translations[index],
    quote: content.quote,
    adapted: true,
    reference,
  }));
}

